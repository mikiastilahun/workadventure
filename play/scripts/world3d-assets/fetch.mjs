/**
 * Downloads the CC0 3D models listed in assets.mjs, optimizes them (textures resized to 512px and converted to
 * WebP) and writes them to public/world3d/models/<id>.glb, with a manifest and the credits.
 *
 *   cd play && npm run fetch-world3d-assets
 *
 * Requires network access. Uses the gltf-transform CLI through npx (no project dependency).
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ASSETS, KENNEY_PACKS } from "./assets.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(here, "../../public/world3d/models");
const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "world3d-assets-"));
const only = process.argv.slice(2);

fs.mkdirSync(outDir, { recursive: true });

function run(command, args, options = {}) {
    execFileSync(command, args, { stdio: ["ignore", "ignore", "inherit"], ...options });
}

function gltfTransform(...args) {
    run("npx", ["-y", "@gltf-transform/cli@4", ...args]);
}

async function download(url, file) {
    const response = await fetch(url);
    if (!response.ok) {
        throw new Error(`Could not download ${url}: ${response.status}`);
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, Buffer.from(await response.arrayBuffer()));
}

async function fetchPolyHaven(asset) {
    const files = await (await fetch(`https://api.polyhaven.com/files/${asset.name}`)).json();
    const gltf = files.gltf["1k"].gltf;
    const dir = path.join(workDir, asset.name);
    const main = path.join(dir, path.basename(gltf.url));
    await download(gltf.url, main);
    for (const [relative, file] of Object.entries(gltf.include)) {
        await download(file.url, path.join(dir, relative));
    }
    return main;
}

const extractedPacks = new Map();
async function fetchKenney(asset) {
    const pack = KENNEY_PACKS[asset.pack];
    let dir = extractedPacks.get(asset.pack);
    if (!dir) {
        dir = path.join(workDir, `kenney-${asset.pack}`);
        const zip = `${dir}.zip`;
        await download(pack.url, zip);
        run("unzip", ["-qo", zip, "-d", dir]);
        extractedPacks.set(asset.pack, dir);
    }
    return path.join(dir, pack.folder, `${asset.name}.glb`);
}

for (const asset of ASSETS) {
    if (only.length > 0 && !only.includes(asset.id)) {
        continue;
    }
    process.stdout.write(`${asset.id} (${asset.source} ${asset.name})... `);
    const source = asset.source === "polyhaven" ? await fetchPolyHaven(asset) : await fetchKenney(asset);
    const step1 = path.join(workDir, `${asset.id}-1.glb`);
    const step2 = path.join(workDir, `${asset.id}-2.glb`);
    const target = path.join(outDir, `${asset.id}.glb`);
    gltfTransform("copy", source, step1);
    gltfTransform("resize", step1, step2, "--width", "512", "--height", "512");
    gltfTransform("webp", step2, step1);
    gltfTransform("prune", step1, step2);
    if (asset.simplify) {
        gltfTransform("weld", step2, step1);
        gltfTransform("simplify", step1, step2, "--ratio", String(asset.simplify), "--error", "0.01");
    }
    gltfTransform("dedup", step2, target);
    const size = fs.statSync(target).size;
    console.log(`${Math.round(size / 1024)} KB`);
}

// The manifest and the credits always describe every model present in the folder
const manifest = {};
const credits = [];
for (const asset of ASSETS) {
    if (!fs.existsSync(path.join(outDir, `${asset.id}.glb`))) {
        continue;
    }
    manifest[asset.id] = {
        file: `${asset.id}.glb`,
        height: asset.height,
        rotation: asset.rotation ?? 0,
        ...(asset.materials ? { materials: asset.materials } : {}),
    };
    credits.push(
        asset.source === "polyhaven"
            ? `- \`${asset.id}.glb\`: "${asset.name}" by Poly Haven, CC0 — https://polyhaven.com/a/${asset.name}`
            : `- \`${asset.id}.glb\`: "${asset.name}" from the Kenney ${asset.pack} kit, CC0 — ${KENNEY_PACKS[asset.pack].page}`,
    );
}
{
    fs.writeFileSync(path.join(outDir, "manifest.json"), JSON.stringify(manifest, null, 4) + "\n");
    fs.writeFileSync(
        path.join(outDir, "CREDITS.md"),
        "# 3D models\n\nAll the models of this folder are in the public domain (CC0). Generated by " +
            "`play/scripts/world3d-assets/fetch.mjs`.\n\n" +
            credits.join("\n") +
            "\n",
    );
}
fs.rmSync(workDir, { recursive: true, force: true });
console.log("Done:", outDir);
